local M = {}

M.pairs = {
  { "(", ")" },
  { "[", "]" },
  { "{", "}" },
  { "<", ">" },
  { "‘", "’" },
  { "“", "”" },
  { "«", "»" },
  { "「", "」" },
  { "（", "）" },
  { '"', '"' },
  { "'", "'" },
  { "`", "`" },
}

M.plain_pairs = {
  { "(", ")" },
  { "[", "]" },
  { "{", "}" },
  { "<", ">" },
  { "‘", "’" },
  { "“", "”" },
  { "«", "»" },
  { "「", "」" },
  { "（", "）" },
}

local aliases = {
  ["("] = { "(", ")" },
  [")"] = { "(", ")" },
  ["["] = { "[", "]" },
  ["]"] = { "[", "]" },
  ["{"] = { "{", "}" },
  ["}"] = { "{", "}" },
  ["<"] = { "<", ">" },
  [">"] = { "<", ">" },
  ['"'] = { '"', '"' },
  ["'"] = { "'", "'" },
  ["`"] = { "`", "`" },
}

function M.for_char(char)
  return aliases[char] or { char, char }
end

return M
